#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const docsDir = join(root, 'docs');
const indexPath = join(docsDir, 'INDEX.md');
const mode = process.argv[2] ?? 'check';

const TYPES = ['tutorial', 'how-to', 'reference', 'explanation'];
const STATUSES = ['draft', 'stable'];
const FOLDER_TYPE = {
  tutorials: 'tutorial',
  'how-to': 'how-to',
  reference: 'reference',
  explanation: 'explanation',
  decisions: 'explanation',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return name.endsWith('.md') ? [full] : [];
  });
}

function parseValue(raw) {
  const v = raw.trim();
  if (v.startsWith('[') && v.endsWith(']')) {
    return v.slice(1, -1).split(',').map((s) => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
  }
  return v.replace(/^["']|["']$/g, '');
}

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return null;
  const data = {};
  for (const line of m[1].split('\n')) {
    const kv = line.replace(/\s+#.*$/, '').match(/^([a-z_]+):\s*(.*)$/);
    if (kv) data[kv[1]] = parseValue(kv[2]);
  }
  return data;
}

function validate(file, fm) {
  const rel = relative(root, file);
  const errors = [];
  if (!fm) return [`${rel}: missing frontmatter block`];
  for (const key of ['title', 'description', 'type', 'audience', 'tags', 'status', 'updated']) {
    if (fm[key] === undefined || fm[key] === '' || (Array.isArray(fm[key]) && fm[key].length === 0)) {
      errors.push(`${rel}: missing "${key}"`);
    }
  }
  if (fm.type && !TYPES.includes(fm.type)) errors.push(`${rel}: type "${fm.type}" not in ${TYPES.join('|')}`);
  if (fm.status && !STATUSES.includes(fm.status)) errors.push(`${rel}: status "${fm.status}" not in ${STATUSES.join('|')}`);
  if (fm.updated && !/^\d{4}-\d{2}-\d{2}$/.test(fm.updated)) errors.push(`${rel}: updated must be YYYY-MM-DD`);
  for (const key of ['audience', 'tags', 'related']) {
    if (fm[key] !== undefined && !Array.isArray(fm[key])) errors.push(`${rel}: "${key}" must be a [list]`);
  }
  const folder = relative(docsDir, file).split(sep)[0];
  const expected = FOLDER_TYPE[folder];
  if (expected && fm.type !== expected) errors.push(`${rel}: lives in docs/${folder}/ so type must be "${expected}"`);
  for (const target of fm.related ?? []) {
    if (!existsSync(join(root, target))) errors.push(`${rel}: related path "${target}" does not exist`);
  }
  return errors;
}

const files = walk(docsDir).filter((f) => f !== indexPath).sort();
const entries = [];
const errors = [];
for (const file of files) {
  const fm = parseFrontmatter(readFileSync(file, 'utf8'));
  errors.push(...validate(file, fm));
  if (fm) entries.push({ path: relative(docsDir, file), ...fm });
}

const lines = [
  '---',
  'title: Documentation index',
  'description: Generated list of every doc with its type, tags and one-line description. Start here.',
  'type: reference',
  'audience: [agent, developer]',
  'tags: [index]',
  'status: stable',
  'updated: generated',
  '---',
  '',
  '# Documentation index',
  '',
  'Generated by `pnpm docs:index` from frontmatter. Do not edit by hand. Conventions are in [CONVENTIONS.md](CONVENTIONS.md).',
  '',
];
const headings = { tutorial: 'Tutorials', 'how-to': 'How-to guides', reference: 'Reference', explanation: 'Explanation' };
for (const type of TYPES) {
  const group = entries.filter((e) => e.type === type);
  if (group.length === 0) continue;
  lines.push(`## ${headings[type]}`, '', '| Doc | Description | Audience | Tags |', '|---|---|---|---|');
  for (const e of group) {
    const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
    lines.push(`| [${cell(e.title)}](${e.path}) | ${cell(e.description)} | ${(e.audience ?? []).join(', ')} | ${(e.tags ?? []).join(', ')} |`);
  }
  lines.push('');
}
const tags = new Map();
for (const e of entries) for (const t of e.tags ?? []) tags.set(t, [...(tags.get(t) ?? []), e]);
lines.push('## By tag', '');
for (const t of [...tags.keys()].sort()) {
  lines.push(`- **${t}**: ${tags.get(t).map((e) => `[${e.title}](${e.path})`).join(', ')}`);
}
lines.push('');
const index = lines.join('\n');

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}
if (mode === 'index') {
  writeFileSync(indexPath, index);
  console.log(`wrote docs/INDEX.md with ${entries.length} docs`);
} else {
  const current = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : '';
  if (current !== index) {
    console.error('docs/INDEX.md is stale. Run `pnpm docs:index`.');
    process.exit(1);
  }
  console.log(`docs ok: ${entries.length} docs, index current`);
}
